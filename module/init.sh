#!/usr/bin/env bash
# Initialise a new external workspace from the shared generic skill set.
#
# Init creates only missing files in the requested external directory. It does
# not clone, switch, or write to the target repository.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
source "$SCRIPT_DIR/common.sh"

usage() {
  cat <<'USAGE'
Usage: init.sh --output PATH --project-name NAME --target PATH [--dry-run]

Create a portable workspace.toml, AGENT.md, and canonical skills directory.
The target path is interpreted relative to the output directory when it is
relative. Existing files are never overwritten.
USAGE
}

OUTPUT=""
PROJECT_NAME=""
TARGET=""
DRY_RUN=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --output|-o)
      [[ $# -ge 2 ]] || die "--output requires a path"
      OUTPUT="$2"
      shift 2
      ;;
    --project-name|-n)
      [[ $# -ge 2 ]] || die "--project-name requires a value"
      PROJECT_NAME="$2"
      shift 2
      ;;
    --target|-t)
      [[ $# -ge 2 ]] || die "--target requires a path"
      TARGET="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      die "unknown argument: $1 (use --help for usage)"
      ;;
  esac
done

[[ -n "$OUTPUT" ]] || { usage >&2; exit 2; }
[[ -n "$PROJECT_NAME" ]] || die "--project-name is required"
[[ -n "$TARGET" ]] || die "--target is required"
[[ "$PROJECT_NAME" != *'"'* ]] || die "project name cannot contain a double quote"
[[ "$TARGET" != *'"'* ]] || die "target path cannot contain a double quote"

OUTPUT_ABS="$(resolve_path "$OUTPUT" "$PWD")"
if [[ "$DRY_RUN" == "0" ]]; then
  # Create the output first so a relative target such as ../project is
  # canonicalised correctly when the output directory did not exist yet.
  mkdir -p "$OUTPUT_ABS"
fi

TARGET_ABS="$(resolve_path "$TARGET" "$OUTPUT_ABS")"
assert_outside_project "$OUTPUT_ABS" "$TARGET_ABS" "output workspace"

if [[ ! -d "$TARGET_ABS" ]]; then
  warn "target project directory does not exist yet: $TARGET_ABS"
fi

if [[ "$DRY_RUN" == "1" ]]; then
  step "would create external workspace at $OUTPUT_ABS"
  step "would target project at $TARGET_ABS"
  exit 0
fi

write_if_missing() {
  local destination="$1"
  local content="$2"
  if [[ -e "$destination" ]]; then
    if [[ -f "$destination" ]] && [[ "$(<"$destination")" == "$content" ]]; then
      ok "$(basename "$destination") already present"
    else
      warn "leaving existing file unchanged: $destination"
    fi
    return
  fi
  printf '%s' "$content" > "$destination"
  ok "created $destination"
}

target_config="${TARGET//\\//}"
project_config="$PROJECT_NAME"

agent_content="# $PROJECT_NAME — external workspace instructions

This file is the canonical project guidance for the external workspace.
Provider projections are generated beside it; the target repository remains
untouched.

Keep project-specific instructions and skills in this workspace. Preserve
unrelated local changes in the target checkout and run the project's own real
checks for every change.

Use Conventional Commits for every project commit with a type, optional
scope, and focused lowercase imperative summary.
"

manifest_content="# Generated by workspace init. Edit paths and project guidance as needed.

project_name = \"$project_config\"
workspace_root = \".\"
target_path = \"$target_config\"

instruction_source = \"AGENT.md\"
instruction_destinations = [\"AGENT.md\", \"AGENTS.md\", \"CLAUDE.md\"]

skills_source = \"skills\"
skill_destinations = [\".agents/skills\", \".claude/skills\"]
"

write_if_missing "$OUTPUT_ABS/AGENT.md" "$agent_content"
write_if_missing "$OUTPUT_ABS/workspace.toml" "$manifest_content"

SOURCE_SKILLS="$SCRIPT_DIR/../skills"
DEST_SKILLS="$OUTPUT_ABS/skills"
mkdir -p "$DEST_SKILLS"
shopt -s nullglob
for skill_dir in "$SOURCE_SKILLS"/*/; do
  skill_name="$(basename "$skill_dir")"
  source_skill="$skill_dir/SKILL.md"
  destination_skill="$DEST_SKILLS/$skill_name/SKILL.md"
  [[ -f "$source_skill" ]] || continue
  if [[ -f "$destination_skill" ]]; then
    if cmp -s "$source_skill" "$destination_skill"; then
      ok "skill '$skill_name' already present"
    else
      warn "leaving existing skill unchanged: $destination_skill"
    fi
    continue
  fi
  mkdir -p "$(dirname "$destination_skill")"
  cp -- "$source_skill" "$destination_skill"
  ok "created skill '$skill_name'"
done

hdr "Done"
ok "workspace initialized"
info "Next: run '$SCRIPT_DIR/bootstrap.sh --config $OUTPUT_ABS/workspace.toml'"
